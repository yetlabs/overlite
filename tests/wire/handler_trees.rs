//! The statements the session runs itself, read from their parse tree: names as
//! Postgres (17) reads them, folded unless quoted.

use std::time::Duration;

use crate::common::*;

// A channel is a name: LISTEN Foo and NOTIFY FOO are both channel foo. The text
// reader kept each as written, and the NOTIFY never arrived.
#[test]
fn a_channel_is_folded_unless_quoted() {
    let addr = start_server();
    let listener = connect(&addr);
    let notifier = connect(&addr);
    listener.exec("LISTEN Foo", &[]).unwrap();
    notifier.exec("NOTIFY FOO, 'it''s'", &[]).unwrap();
    let n = listener.wait_for_notification(Duration::from_secs(3)).unwrap();
    assert_eq!((n.channel.as_str(), n.payload.as_str()), ("foo", "it's"));
    listener.exec(r#"LISTEN "Bar Baz""#, &[]).unwrap();
    notifier.exec(r#"NOTIFY "Bar Baz""#, &[]).unwrap();
    let n = listener.wait_for_notification(Duration::from_secs(3)).unwrap();
    assert_eq!(n.channel, "Bar Baz");
    listener.exec("UNLISTEN *", &[]).unwrap();
    notifier.exec("NOTIFY foo", &[]).unwrap();
    listener
        .wait_for_notification(Duration::from_millis(300))
        .expect_err("no notification after UNLISTEN *");
}

// A prepared statement's name is folded unless quoted, as Postgres reads it: PREPARE
// byId and EXECUTE BYID name one statement, which the text reader kept apart.
#[test]
fn a_prepared_statement_name_is_folded_unless_quoted() {
    let conn = connect(&start_server());
    must_exec(&conn, "CREATE TABLE t (id int, name text)");
    must_exec(&conn, "INSERT INTO t VALUES (1, 'a'), (2, 'b, c')");
    must_exec(
        &conn,
        "PREPARE byId (int, text) AS SELECT name FROM t WHERE id = $1 OR name = $2",
    );
    assert_eq!(query_column(&conn, "EXECUTE BYID (1, 'b, c')", 0), ["a", "b, c"]);
    must_exec(&conn, r#"PREPARE "Q" AS SELECT 'x'"#);
    assert_eq!(query_column(&conn, r#"EXECUTE "Q""#, 0), ["x"]);
    assert_eq!(conn.exec("EXECUTE q", &[]).unwrap_err().code(), "26000");
    must_exec(&conn, "DEALLOCATE byid");
    assert_eq!(conn.exec("EXECUTE byId (1, 'x')", &[]).unwrap_err().code(), "26000");
}

// COMMENT ON names its object as Postgres reads it, and an empty comment drops the
// comment, as NULL does: the text reader stored an empty one.
#[test]
fn comment_on_reads_its_object_and_drops_an_empty_comment() {
    let conn = connect(&start_server());
    must_exec(&conn, "CREATE SEQUENCE s2 START WITH 100");
    must_exec(
        &conn,
        r#"CREATE TABLE "My T" (id int, CONSTRAINT "c 1" CHECK (id > 0))"#,
    );
    must_exec(&conn, r#"COMMENT ON TABLE "My T" IS 'a table'"#);
    must_exec(&conn, r#"COMMENT ON COLUMN "My T".id IS 'the id'"#);
    let described = |q: &str| query_column(&conn, q, 0);
    assert_eq!(
        described(r#"SELECT obj_description('"My T"'::regclass, 'pg_class')"#),
        ["a table"]
    );
    assert_eq!(
        described(r#"SELECT col_description('"My T"'::regclass, 1)"#),
        ["the id"]
    );
    must_exec(&conn, r#"COMMENT ON TABLE "My T" IS ''"#);
    assert_eq!(
        described(r#"SELECT coalesce(obj_description('"My T"'::regclass, 'pg_class'), 'none')"#),
        ["none"]
    );
    must_exec(&conn, r#"COMMENT ON CONSTRAINT "c 1" ON "My T" IS 'positive'"#);
    let err = conn
        .exec(r#"COMMENT ON CONSTRAINT nope ON "My T" IS 'x'"#, &[])
        .unwrap_err();
    assert_eq!(err.code(), "42704");
}

// ALTER SEQUENCE IF EXISTS s altered a sequence named "if", and any ALTER SEQUENCE
// without CYCLE turned a cycling sequence's CYCLE off.
#[test]
fn alter_sequence_reads_its_name_and_options() {
    let conn = connect(&start_server());
    must_exec(&conn, "CREATE SEQUENCE s");
    must_exec(&conn, "ALTER SEQUENCE IF EXISTS s INCREMENT BY 5");
    let next = |seq: &str| query_column(&conn, &format!("SELECT nextval('{seq}')::text"), 0);
    assert_eq!((next("s"), next("s")), (vec!["1".to_string()], vec!["6".to_string()]));
    must_exec(&conn, "CREATE SEQUENCE c MAXVALUE 2 CYCLE");
    must_exec(&conn, "ALTER SEQUENCE c INCREMENT BY 1");
    assert_eq!([next("c"), next("c"), next("c")].concat(), ["1", "2", "1"]);
}

// A table named with a space and a serial or identity column: the text reader took
// the table for its first word, and the column's sequence and default were kept under
// that name, so an INSERT leaving the column out wrote NULL into it.
#[test]
fn a_serial_column_of_a_table_named_with_a_space() {
    let conn = connect(&start_server());
    must_exec(&conn, "CREATE SEQUENCE s2 START WITH 100");
    must_exec(
        &conn,
        r#"CREATE TABLE "My T" (id int, n serial, m int GENERATED BY DEFAULT AS IDENTITY (START WITH 10), k bigint DEFAULT nextval('s2'))"#,
    );
    must_exec(&conn, r#"INSERT INTO "My T" (id) VALUES (1), (2)"#);
    assert_eq!(
        query_column(&conn, r#"SELECT n || ',' || m || ',' || k FROM "My T" ORDER BY id"#, 0),
        ["1,10,100", "2,11,101"]
    );
    assert_eq!(
        query_column(&conn, r#"SELECT pg_get_serial_sequence('"My T"', 'n')"#, 0),
        [r#"public."My T_n_seq""#]
    );
}
